-- После какого движения начат заход. Круг шага — заходы после движения,
-- открывшего круг, а кнопка владельца и заход после неё пишутся в одну
-- секунду (клик исполняется тем же проходом движка): по времени «строго
-- позже» такой заход выпадал из круга, и предел давал на заход больше
-- (T37, 2026-09-10: движение 240 и заход 166 — оба 02:13:53). Номер
-- движения упорядочивает их всегда.
ALTER TABLE run ADD COLUMN after_move INTEGER;

-- Старые заходы: последнее движение не позже старта. «Не позже», а не
-- «раньше»: в одну секунду сначала движение, потом заход — так работает
-- проход движка.
UPDATE run SET after_move = (
  SELECT MAX(m.id) FROM move m
   WHERE m.task_id = run.task_id AND m.at <= run.started_at
) WHERE after_move IS NULL;
