#!/usr/bin/env bash
#
# Завести новую машину со своей рабочей машины: вписать в реестр, подтвердить
# отпечаток ключа, настроить.
#
#   new.sh ИМЯ ПУБЛИЧНЫЙ-АДРЕС [провайдер] [железо]
#
# То же самое делается через GitHub, без единого локального запуска —
# см. README, «Установка». Эта команда для тех случаев, когда удобнее
# одной строкой.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

NAME="${1:-}"
ADDR="${2:-}"
PROVIDER="${3:-}"
HARDWARE="${4:-}"
REGISTRY="${ROOT_DIR}/servers.yml"

[ -n "$NAME" ] && [ -n "$ADDR" ] || die "Как звать машину и какой у неё публичный адрес?
  make new h=vps-dev-fsn1 ip=1.2.3.4"

# Имя должно годиться и для имени узла в частной сети, и для имени переменной
# в .env: там оно станет суффиксом у пароля root этой машины.
[[ "$NAME" =~ ^[a-z0-9][a-z0-9-]*$ ]] || die "Имя машины: строчные буквы, цифры и дефис."

grep -qE "^        ${NAME}:" "$REGISTRY" && die "Машина ${NAME} уже есть в реестре."
[ -t 0 ] || die "Заводить машину без терминала нельзя: надо подтвердить отпечаток ключа."

# --- Отпечаток: подтверждает человек ----------------------------------------
#
# Машина могла уже войти в частную сеть — тогда идём по ней. Не вошла —
# по публичному адресу.
probe="$(discover_tailnet_address "$NAME")"
[ -n "$probe" ] || probe="$ADDR"

keys="$(host_keys_at "$probe" || true)"
[ -n "$keys" ] || die "Машина ${NAME} (${probe}) не отвечает на порту 22.
  Если она должна была войти в частную сеть сама — проверь, появилась ли она там."

fingerprint="$(printf '%s\n' "$keys" | ssh-keygen -lf - 2>/dev/null \
    | awk '$4 == "(ED25519)" {print $2}' | head -1)"
[ -n "$fingerprint" ] || die "Не смог получить отпечаток ключа машины ${NAME}."

echo ""
echo "→ Отпечаток ключа машины ${NAME}:"
echo ""
echo "    ${fingerprint}"
echo ""
echo "  Сверь его с тем, что показывает веб-консоль провайдера:"
echo "    ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub"
read -rp "Совпадает? [y/N] " ok
[ "$ok" = "y" ] || die "Отменено."

# --- Вписать в реестр --------------------------------------------------------
#
# Вставляем блок перед строкой `      vars:` — это конец перечня машин.
# Формат реестра простой и наш собственный, поэтому обходимся без библиотеки
# для правки YAML: она потянула бы зависимость в образ, а комментарии в файле
# всё равно сохраняет плохо.
block="        ${NAME}:
          dev_public_address: ${ADDR}
          dev_host_fingerprint: \"${fingerprint}\""
[ -n "$PROVIDER" ] && block="${block}
          dev_provider: ${PROVIDER}"
[ -n "$HARDWARE" ] && block="${block}
          dev_hardware: \"${HARDWARE}\""

tmp="$(mktemp)"
awk -v block="$block" '
    /^      vars:$/ && !done { print block; print ""; done = 1 }
    { print }
' "$REGISTRY" > "$tmp"

grep -qE "^        ${NAME}:" "$tmp" || { rm -f "$tmp"; die "Не смог вписать машину в реестр. Впиши руками."; }
mv "$tmp" "$REGISTRY"
say "Машина ${NAME} вписана в servers.yml"

# --- Настроить ---------------------------------------------------------------
#
# Секретов здесь не заводим отдельным шагом, как у боевого сервера
# (там был make secrets — расшифровка SOPS перед прогоном): в этом проекте
# секреты не шифруются, они уже лежат в .env или в окружении CI, и
# run-playbook.sh достаёт их сам через lib.sh.
echo ""
"${ROOT_DIR}/scripts/run-playbook.sh" --host "$NAME"

echo ""
echo "══════ Осталось ══════"
echo "  1. Проверить: make audit h=${NAME}"
echo "  2. Записать машину в git:"
echo "       git add servers.yml"
echo "       git commit -m 'машина ${NAME}' && git push"
echo "  3. Если выкатка выше напечатала другой отпечаток ключа — впиши его"
echo "     в блок машины в servers.yml: dev_host_fingerprint"
