#!/usr/bin/env bash
#
# Проверить настройку независимыми инструментами и дать вердикт.
#
# Раньше эта команда печатала простыню и всегда возвращала успех: в скрипт
# и в CI её поставить было нельзя, а глазами простыню читают невнимательно.
# Теперь каждая проверка имеет исход, а команда возвращает ненулевой код,
# если что-то не так.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

# Версии закреплены по той же причине, что и версии в runner/Dockerfile:
# проверка безопасности не должна менять поведение сама по себе.
readonly NMAP_IMAGE="instrumentisto/nmap:7.98"
readonly SSH_AUDIT_IMAGE="positronsecurity/ssh-audit:v3.2.0"

# У боевого сервера здесь были два списка портов: «запрещённые никогда»
# и «22 закрыт, 80/443 открыты только для Cloudflare». У этого сервера
# смысл проверки перевёрнут: он не открыт публике ВООБЩЕ, ни одним портом,
# включая 22, 80 и 443. Поэтому список один, и правильный исход по нему —
# пусто.
#
# Сканируем не весь диапазон, а тот, где реально может что-то оказаться.
# Список не «типичных портов» из головы, а вывод из устройства машины:
#
#   22, 80, 443   единственные, что вообще открывались когда-либо
#   8000-8999     блоки, которые раздаёт `ports claim` (LO=8010, HI=8999),
#                 плюс заповедник инфраструктуры 8060-8069
#   9000-9999     теневые порты общего прокси (порт службы + 1000)
#
# Именно сюда попадёт контейнер, опубликованный на 0.0.0.0 вместо 127.0.0.1, —
# то есть ровно та ошибка, от которой стоит правило DOCKER-USER. Полный скан
# 1-65535 против машины, которая всё отбрасывает молча, идёт минутами
# на таймаутах и ничего сверх этого не находит.
#
# Полный скан доступен явно: audit.sh <машина> --full
SCAN_PORTS="-p22,80,443,8000-8999,9000-9999"

# --full — весь диапазон 1-65535. Идёт минутами на таймаутах, потому что
# машина всё отбрасывает молча, зато не полагается на список выше. Держать
# как отдельную команду, а не как обычный режим: раз в квартал полезно,
# в каждом прогоне — только повод перестать запускать проверку вовсе.
args=()
for a in "$@"; do
    case "$a" in
        --full) SCAN_PORTS="-p-" ;;
        *)      args+=("$a") ;;
    esac
done
set -- "${args[@]+"${args[@]}"}"
readonly SCAN_PORTS

load_servers
pick_targets "${1:-}" all
targets=("${PICKED[@]}")

PROBLEMS=()

audit_one() {
    local name="$1" addr conn scan open_ports
    addr="$(server_public_address "$name")"
    conn="$(server_address "$name")"

    echo ""
    echo "══════ ${name} ══════"
    echo "  публичный адрес: ${addr}"
    echo "  подключаюсь по:  ${conn}"
    echo ""

    # Без этого проверка подключения падает на непроверенном ключе хоста —
    # в CI файла known_hosts нет вовсе.
    ensure_known_host "$name" "$conn"

    echo "→ Сервер отвечает"
    if ansible_run ansible "$name" -e ansible_host="$conn" -m ping -o >/dev/null 2>&1; then
        echo "  ✔ отвечает"
    else
        echo "  ✖ не отвечает"
        PROBLEMS+=("${name}: сервер не отвечает")
        # Дальше всё равно идём: «что видно снаружи» не зависит от того,
        # пустил ли нас сервер, а это самая важная часть проверки.
    fi

    echo ""
    echo "→ Что видно снаружи"
    # Сканируем ПУБЛИЧНЫЙ адрес, а не тот, по которому подключаемся: после
    # входа машины в частную сеть подключение идёт через неё, а проверять
    # надо то, что видно из интернета.
    scan="$(docker run --rm --network host "$NMAP_IMAGE" -Pn -T4 \
        "$SCAN_PORTS" "$addr" 2>/dev/null \
        | grep -E "^[0-9]+/" || true)"
    [ -n "$scan" ] || { echo "  ✖ сканирование не дало результата"; PROBLEMS+=("${name}: не удалось просканировать порты"); return 1; }
    printf '%s\n' "$scan" | sed 's/^/  /'
    open_ports="$(printf '%s\n' "$scan" | awk '$2 == "open" {sub("/tcp","",$1); print $1}')"

    echo ""
    if [ -n "$open_ports" ]; then
        # Любой открытый порт — проблема, без исключений. Порт 22 нужен
        # только при первой настройке, пока машины нет в частной сети;
        # роль firewall закрывает его вместе со всеми остальными сразу,
        # как только Tailscale поднялся. Открытым он остаётся, если
        # настройка не дошла до конца или Tailscale не поднялся.
        echo "  ✖ снаружи отвечают порты: $(printf '%s' "$open_ports" | tr '\n' ' ')"
        echo "    Эта машина не должна отвечать наружу ни одним портом."
        echo "    Если среди них 22 — прогони apply и посмотри, что говорит"
        echo "    роль firewall; остальные не должна открывать ни одна роль."
        PROBLEMS+=("${name}: снаружи отвечают порты $(printf '%s' "$open_ports" | tr '\n' ' ')")
    else
        echo "  ✔ снаружи не отвечает ни один порт"
    fi

    echo ""
    echo "→ Крепость SSH"
    if docker run --rm "$SSH_AUDIT_IMAGE" --skip-rate-test -L "$addr" >/dev/null 2>&1; then
        echo "  ✔ замечаний нет"
    else
        docker run --rm "$SSH_AUDIT_IMAGE" --skip-rate-test "$addr" 2>/dev/null \
            | grep -E "\(fail\)|\(warn\)" | sed 's/^/  /' || true
        echo "  (полный разбор: docker run --rm ${SSH_AUDIT_IMAGE} ${addr})"
    fi

    echo ""
    echo "→ Настройки Docker"
    # Через grep, а не через --format: фигурные скобки шаблона Go Ansible
    # принимает за свой шаблон и падает. Раньше ошибка глушилась через
    # `|| true`, и эта проверка не выполнялась ни разу.
    if ansible_run ansible "$name" -e ansible_host="$conn" -b -m shell \
        -a 'docker info 2>/dev/null | grep -E "Logging Driver|Containers:"' 2>/dev/null \
        | grep -E "Logging Driver|Containers:" | sed 's/^/  /'; then
        :
    else
        echo "  ✖ не удалось спросить Docker"
        PROBLEMS+=("${name}: Docker не ответил")
    fi
}

for name in "${targets[@]}"; do
    audit_one "$name" || true
done

echo ""
echo "══════ Вердикт ══════"
#
# Одна корзина, а не две. У боевого сервера рядом с «Проблемами» жили
# «Замечания», и вердикт смотрел только на первые — а именно в замечаниях
# лежали худшие находки. Корзина «замечаний» здесь не заводится вовсе:
# всё, что аудит считает неправильным, обязано валить прогон.
if [ "${#PROBLEMS[@]}" -gt 0 ]; then
    echo ""
    echo "Проблемы:"
    printf '  ✖ %s\n' "${PROBLEMS[@]}"
    echo ""
    exit 1
fi
echo "  ✔ снаружи не отвечает ничего, замечаний нет"
