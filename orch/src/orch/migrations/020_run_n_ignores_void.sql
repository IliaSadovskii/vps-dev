-- Номер захода считается среди живых заходов, а не всех бывших. Возврат
-- начисто затирает работу шага и начинает его заново — для роли и для
-- владельца это первый заход, а не третий: старые забыты, их файлов нет, и
-- предел заходов уже считается заново. Уникальность номера при этом нужна,
-- иначе два живых захода встанут под одним именем, — поэтому индекс
-- частичный: забытые заходы в него не входят.
DROP INDEX IF EXISTS run_task_step_n;
CREATE UNIQUE INDEX run_task_step_n ON run(task_id, step, n) WHERE void_at IS NULL;
