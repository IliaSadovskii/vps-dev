#!/usr/bin/env bash
#
# Обновить доску Kandev из репозитория. Запускается НА сервере: смысл этой
# команды ровно в том, чтобы не идти на машину снаружи — ни через SSH,
# ни через раннер GitHub. Полная выкатка тратит две-три минуты на то, чтобы
# попасть на машину, а эта работа не требует туда попадать.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

[ -x /usr/local/bin/ansible-playbook ] \
    || die "Ansible на машине нет: эта команда работает только НА сервере (его ставит роль pull). Снаружи: make apply t=seed."

# Сначала подтянуть правки, потом применить. Если правили на GitHub —
# без этого шага применилось бы то, что лежит здесь, а не то, что там.
#
# --ff-only намеренно: расхождение между тем, что правили здесь, и тем, что
# правили на GitHub, должно останавливать работу вопросом, а не разрешаться
# слиянием за спиной у владельца.
say "Забираю правки из репозитория"
git -C "$ROOT_DIR" pull --ff-only \
    || die "git pull не прошёл начисто. Здесь и на GitHub правили порознь — разберите расхождение руками."

say "Применяю наполнение доски"
cd "${ROOT_DIR}/ansible"
ANSIBLE_CONFIG=ansible.cfg \
ANSIBLE_FORCE_COLOR=1 \
    /usr/local/bin/ansible-playbook -i localhost, board.yml
