-- Сдан ли ход сигналом. Пустой `outcome` значит две разные вещи: шаг с
-- одним переходом (исход не называется) и ход, кончившийся молча. Выводить
-- это из таблицы `move` можно, но неоднозначно: после второго захода в тот
-- же шаг движение нельзя надёжно отнести к нужному заходу. Это факт захода,
-- а не производное состояние, поэтому он живёт в строке.
ALTER TABLE run ADD COLUMN signalled INTEGER NOT NULL DEFAULT 0;

-- Прошлые заходы: сигнал был, если у захода есть исход либо задача из этого
-- шага уехала. Для уже закрытых задач точность не важна, важна честность
-- будущих цифр `orch stats`.
UPDATE run SET signalled = 1 WHERE outcome IS NOT NULL;
